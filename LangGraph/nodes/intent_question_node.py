STOPWORDS = set(["의", "를", "은", "는", "이", "가", "좀", "알려줘", "말해줘", "알려", "줘", "해줘", "에", "에서", "과", "및"])
KO_PATTERN = re.compile(r"[가-힣]")

def detect_language(text: str) -> Literal["ko", "en", "unknown"]:
    if re.search(r"[가-힣]", text or ""):
        return "ko"
    if re.search(r"[A-Za-z]", text or ""):
        return "en"
    return "unknown"

def norm_key(s: str) -> str:
    s = str(s).strip().lower()
    s = re.sub(r"[\s\-\_]+","", s)
    s = s.replace("bank","은행")
    return s

def simple_tokenize(text: str) -> List[str]:
    tokens = re.split(r"[^0-9A-Za-z가-힣+/·\.]+", (text or "").lower())
    tokens = [t for t in tokens if t and t not in STOPWORDS]
    return tokens

def find_bank(tokens: List[str], raw: str) -> Optional[str]:
    for k, v in BANK_ALIASES.items():
        if k in raw or k in tokens or norm_key(k) in raw or norm_key(k) in "".join(tokens):
            return v
    nk = norm_key(raw)
    if nk in BANK_ALIASES: return BANK_ALIASES[nk]
    return None

def find_product(tokens: List[str], raw: str) -> Optional[str]:
    for k, v in PRODUCT_ALIASES.items():
        if k in raw or k in tokens or norm_key(k) in raw or norm_key(k) in "".join(tokens):
            return v
    m = re.search(r"([가-힣A-Za-z0-9]+)\s*(정기예금|예금|적금|대출)", raw)
    if m:
        cand = (m.group(1) + " " + m.group(2)).strip()
        nk = norm_key(cand)
        return PRODUCT_ALIASES.get(nk, cand)
    return None

def extract_clause_tags(raw: str):
    tags = []
    hit_keywords = []
    raw_lower = raw.lower()
    for tag, kws in CLAUSE_KEYWORDS.items():
        for kw in kws:
            if kw in raw or kw in raw_lower:
                if tag not in tags: tags.append(tag)
                hit_keywords.append(kw)
    return tags, hit_keywords

def classify_intent(tags: List[str], raw: str) -> Intent:
    if "비교" in raw or "vs" in raw.lower():
        return "compare"
    if any(t in tags for t in ["rate","fee","early_close","preferential","eligibility"]):
        return "rate_fee_lookup" if ("rate" in tags or "fee" in tags) else "clause_lookup"
    if any(k in raw for k in ["정의","뭐야","무엇"]):
        return "definition"
    return "clause_lookup" if tags else "other"

def detect_applicability_hint(bank: Optional[str], product: Optional[str], tags: List[str]) -> Optional[bool]:
    if "rate" in tags:
        p = (product or "").lower()
        b = (bank or "").lower()
        if any(x in p for x in ["월렛","wallet","페이","pay"]) or any(x in b for x in ["월렛","wallet","페이","pay"]):
            return False
    return None

def intent_node(state: Dict[str, Any], llm: Any = None) -> Dict[str, Any]:
    q: str = state.get("question","") or ""
    lang = detect_language(q)
    tokens = simple_tokenize(q)
    bank = find_bank(tokens, q)
    product = find_product(tokens, q)
    clause_tags, hit_keywords = extract_clause_tags(q)
    intent = classify_intent(clause_tags, q)

    applicability_hint = detect_applicability_hint(bank, product, clause_tags)

    product_type = None
    if re.search(r"정기예금|예금", q): product_type = "예금"
    elif "적금" in q: product_type = "적금"
    elif "대출" in q: product_type = "대출"

    state.update({
        "bank_name": bank,
        "product_name": product,
        "product_type": product_type,
        "clause_keywords": clause_tags,
        "raw_keywords": hit_keywords,
        "applicability_hint": applicability_hint,
    })
    return state

def intent_question_node(state: Dict[str, Any], deps: Any = None) -> Dict[str, Any]:
    """사용자 질문에서 은행/상품 단서를 추출하고 intent를 파악한다."""
    return intent_node(state)
